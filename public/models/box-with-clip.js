const {
  draw,
  drawRoundedRectangle,
  makeSolid,
  makeFace,
  assembleWire,
  EdgeFinder,
} = replicad;

export const defaultParams = {
  width: 50,
  height: 100,

  depth: 15,

  wallThickness: 1.6,
  outerFillet: 5,
  bottomFillet: 1,

  tolerance: 0.3,
};

function profileBox(inputProfile, base) {
  const start = inputProfile.blueprint.firstPoint;
  const profile = inputProfile.translate(-start[0], -start[1]);

  const end = profile.blueprint.lastPoint;

  const baseSketch = base.sketchOnPlane();

  // We create the side of the box
  const side = baseSketch.clone().sweepSketch(
    plane => {
      return profile.sketchOnPlane(plane);
    },
    {
      withContact: true,
    }
  );

  // We put all the pieces together
  return makeSolid([
    side,
    // The face generated by sweeping the end of the profile
    makeFace(assembleWire(new EdgeFinder().inPlane("XY", end[1]).find(side))),
    // The face generated by the base
    baseSketch.face(),
  ]);
}

function tray({
  width,
  height,
  depth,
  wallThickness,
  outerFillet,
  bottomFillet,
}) {
  const base = drawRoundedRectangle(
    width - 2 * bottomFillet,
    height - 2 * bottomFillet,
    outerFillet
  );

  const profile = draw()
    .line(bottomFillet, bottomFillet)
    .customCorner(bottomFillet)
    .vLine(depth - bottomFillet)
    .hLine(-wallThickness)
    .vLine(-depth + wallThickness / 2 + bottomFillet)
    .customCorner(bottomFillet - wallThickness)
    .lineTo([0, wallThickness])
    .done();

  return profileBox(profile, base).fillet(wallThickness / 3, e =>
    e.inPlane("XY", depth)
  );
}

export default function main({
  width,
  height,
  depth,
  bottomThickness,
  wallThickness,
  tolerance,
  outerFillet,
  bottomFillet,
}) {
  const trayShape = tray({
    width,
    height,
    depth,
    wallThickness,
    outerFillet,
    bottomFillet,
  });

  const lid = drawRoundedRectangle(width, height, outerFillet + bottomFillet)
    .sketchOnPlane()
    .extrude(wallThickness);

  const tag = draw([-5, 0])
    .vLine(depth / 2)
    .customCorner(2)
    .hLine(10)
    .customCorner(2)
    .vLineTo(0)
    .close()
    .sketchOnPlane("XZ")
    .extrude(wallThickness)
    .chamfer(wallThickness / 2, e => e.inPlane("XZ", wallThickness));

  return tag;

  return [
    {
      shape: trayShape,
      name: "Tray",
    },
    lid,
  ];
}
